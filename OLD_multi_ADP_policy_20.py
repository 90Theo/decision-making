
#  Task 4 (v2): Multi-Stage Approximate Dynamic Programming
#
#  ADP ARCHITECTURE OVERVIEW
#  ─────────────────────
#  MULTI-STAGE deployment MILP.
#  The value function approximation (VFA) and training
#
#    V̂_t(s ; θ_t) = θ_t ᵀ φ(s)      [linear in weights θ, nonlinear in s OK]


#  v1 (1-step):   min  c_t(a_t)  +  θ_{t+1}ᵀ φ(s̃_{t+1})           
#                                                                     
#   v2 (L-step):   min  Σ_{τ=0}^{L-1} c_{t+τ}(a_{t+τ})              
#                           + θ_{t+L}ᵀ φ(s̃_{t+L})                      
                                                                  
#  The first L stages are optimised EXPLICITLY with full dynamics.   
#   The VFA captures all costs BEYOND the lookahead horizon.          


#
#  MILP structure at deployment
#  ────────────────────────────
#  Decision variables:   p1[τ], p2[τ], v[τ]   for τ = 0, …, L-1
#  State variables:      T1[τ], T2[τ], H[τ], vc[τ]   for τ = 0, …, L
#                        (τ=0 is the current observed state, fixed)
#  Auxiliary variables:  z1[L], z2[L]  for the VFA cold-risk features
#
#  Stochastic inputs (price, occupancy) are replaced by their EXPECTED
#  values at each future stage — the same certainty-equivalent approach
#  used in the 1-step version, just extended over more steps.

