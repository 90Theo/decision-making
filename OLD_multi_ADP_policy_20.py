# SECTION 1 — CONSTANTS & SYSTEM PARAMETERS
# ═══════════════════════════════════════════════════════════════════════

PARAMS   = get_fixed_data()
T_SLOTS  = int(PARAMS['num_timeslots'])   # 10 hours

# VFA hyperparameters
# N_SCENARIOS is set lower than v1 (50 vs 200) because on-policy training is
# more data-efficient: each trajectory is generated by the deployment policy,
# so there is no off-policy mismatch to overcome.  50 scenarios × 10 steps
# gives 500 data points for a 12-feature ridge regression — statistically solid.
# With Gurobi (100× faster than HiGHS), 200 scenarios is feasible in <5 s.
N_FEATURES   = 12
N_SCENARIOS  = 2000    # training scenarios (used by offline training script)
N_ITER       = 5
RIDGE_ALPHA  = 1e-2




# Multi-stage lookahead depth
# L=5: explicit optimisation over 5 stages + VFA terminal for remaining 5
LOOKAHEAD_STEPS = 3

# Epsilon margin: added to T_LOW inside the MILP to create a safety buffer
# against forecast error. Prevents accidental overrule trigger from
# certainty-equivalent forecasts being slightly off.
EPSILON_TEMP = 0.5   # °C buffer above T_LOW




# ═══════════════════════════════════════════════════════════════════════
# SECTION 2 — FEATURE FUNCTION  φ(s) 


def compute_features(state):
    """
    Returns φ(s) ∈ ℝ^12.  Same feature map as the 1-step ADP.

    Feature index  |  φ_k(s)                        |  Why it matters
    ───────────────┼─────────────────────────────────┼──────────────────────────
     0             |  1   (bias)                     |  baseline cost offset
     1             |  T1 / 25                        |  room 1 temp
     2             |  T2 / 25                        |  room 2 temp
     3             |  H  / 50                        |  humidity
     4             |  λ  / 6                         |  current price
     5             |  λ_prev / 6                     |  price momentum
     6             |  κ1 / 35                        |  occupancy room 1
     7             |  κ2 / 35                        |  occupancy room 2
     8             |  t  / 10                        |  time-to-go
     9             |  c_vent / 3                     |  ventilation lock-in
    10             |  max(0, T_low − T1) / 5         |  cold risk r1
    11             |  max(0, T_low − T2) / 5         |  cold risk r2
    """
    T_LOW = PARAMS['temp_min_comfort_threshold']
    phi = np.array([
        1.0,
        state['T1']             / 25.0,
        state['T2']             / 25.0,
        state['H']              / 50.0,
        state['price_t']        / 6.0,
        state['price_previous'] / 6.0,
        state['Occ1']           / 35.0,
        state['Occ2']           / 35.0,
        state['current_time']   / float(T_SLOTS),
        min(state['vent_counter'], 3) / 3.0,
        max(0.0, T_LOW - state['T1']) / 5.0,
        max(0.0, T_LOW - state['T2']) / 5.0,
    ], dtype=float)
    return phi


