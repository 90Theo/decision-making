# SECTION 8 — POLICY ENTRY POINT
# ═══════════════════════════════════════════════════════════════════════

def select_action(state):
    """
    Multi-stage ADP policy.

    At each hour t, solve an L-step lookahead MILP that:
      1. Optimises decisions explicitly over L stages
      2. Uses expected prices and occupancies as certainty equivalents
      3. Attaches the learned VFA θ_{t+L}ᵀφ(s̃_{t+L}) as terminal value

    Only the here-and-now decision (τ=0) is returned and executed.
    The remaining L-1 decisions are discarded (rolling horizon).

    Parameters
    ----------
    state : dict — current environment state

    Returns
    -------
    dict with keys  HeatPowerRoom1, HeatPowerRoom2, VentilationON
    """
    t = int(state['current_time'])

    # Adapt lookahead to remaining horizon
    remaining = T_SLOTS - t
    L = min(LOOKAHEAD_STEPS, remaining)

    if L <= 0:
        # No decisions left
        return {'HeatPowerRoom1': 0.0, 'HeatPowerRoom2': 0.0, 'VentilationON': 0}

    if L == 1:
        # Fall back to 1-step MILP (identical to v1)
        theta_next = _THETA_LIST[t + 1] if t + 1 < T_SLOTS \
                     else np.zeros(N_FEATURES)
        return _solve_1step_MILP(state, theta_next)

    return _solve_multistage_MILP(state, _THETA_LIST, L)
